"""Database tables.

Privacy rule: this database never learns who a home belongs to. A home is an opaque UUID
plus an operator-chosen code like "home-007". Names, addresses and phone numbers belong in
billing/CRM, never here.

Clock rule: every timestamp the watchdog reasons about (last_heartbeat_at, status changes,
alert times) comes from the database server's clock. A Raspberry Pi has no real-time clock
and can boot with the wrong time, so agent-supplied times are stored for diagnostics only.
"""

import uuid
from datetime import datetime

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    DateTime,
    Double,
    ForeignKey,
    Identity,
    Index,
    MetaData,
    String,
    Text,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

HOME_STATUSES = ("pending", "ok", "degraded", "offline")
ALERT_KINDS = ("offline", "degraded", "recovered")


class Base(DeclarativeBase):
    # Predictable constraint names keep Alembic migrations stable across environments.
    metadata = MetaData(
        naming_convention={
            "ix": "ix_%(column_0_label)s",
            "uq": "uq_%(table_name)s_%(column_0_name)s",
            "ck": "ck_%(table_name)s_%(constraint_name)s",
            "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
            "pk": "pk_%(table_name)s",
        }
    )
    type_annotation_map = {datetime: DateTime(timezone=True)}


def _in_list(column: str, values: tuple[str, ...]) -> str:
    return f"{column} IN ({', '.join(repr(v) for v in values)})"


class Home(Base):
    __tablename__ = "homes"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    label: Mapped[str] = mapped_column(String(40), unique=True)
    # SHA-256 of the API key. The key itself is shown once at creation and never stored.
    api_key_hash: Mapped[str] = mapped_column(String(64), unique=True)
    api_key_hint: Mapped[str] = mapped_column(String(16))  # "hwk_3f9a1c2b" — safe to display
    active: Mapped[bool] = mapped_column(server_default=text("true"))
    offline_after_s: Mapped[int] = mapped_column(server_default=text("300"))

    # Written by the heartbeat endpoint.
    last_heartbeat_at: Mapped[datetime | None]
    last_healthy_at: Mapped[datetime | None]  # last heartbeat where Home Assistant answered

    # Written only by the watchdog (single writer = simple reasoning).
    status: Mapped[str] = mapped_column(String(16), server_default=text("'pending'"))
    status_changed_at: Mapped[datetime] = mapped_column(server_default=func.now())
    # Start of the current monitoring gap (the last good signal before the home went
    # offline/degraded). Cleared on recovery. Lets the recovery alert say how long the
    # home was actually unmonitored, not just how long it sat in one status.
    problem_since: Mapped[datetime | None]

    created_at: Mapped[datetime] = mapped_column(server_default=func.now())

    __table_args__ = (
        CheckConstraint(_in_list("status", HOME_STATUSES), name="status"),
        CheckConstraint("offline_after_s BETWEEN 5 AND 86400", name="offline_after_s"),
        CheckConstraint("label ~ '^[a-z0-9][a-z0-9-]{1,38}[a-z0-9]$'", name="label"),
    )


class Heartbeat(Base):
    __tablename__ = "heartbeats"

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    home_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("homes.id", ondelete="CASCADE"))
    received_at: Mapped[datetime] = mapped_column(server_default=func.now())
    sent_at: Mapped[datetime]  # agent clock — diagnostics only
    agent_version: Mapped[str] = mapped_column(String(32))
    ha_ok: Mapped[bool]
    outbox_depth: Mapped[int]
    dead_letters: Mapped[int]

    __table_args__ = (Index("ix_heartbeats_home_id_received_at", "home_id", "received_at"),)


class Event(Base):
    """One sensor state change forwarded by a home's agent."""

    __tablename__ = "events"

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    home_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("homes.id", ondelete="CASCADE"))
    event_id: Mapped[uuid.UUID]  # idempotency key generated by the agent
    entity_id: Mapped[str] = mapped_column(String(255))
    state: Mapped[str] = mapped_column(String(255))
    value: Mapped[float | None] = mapped_column(Double)  # the state as a number, when it is one
    device_class: Mapped[str | None] = mapped_column(String(64))
    unit: Mapped[str | None] = mapped_column(String(32))
    occurred_at: Mapped[datetime]  # Home Assistant's last_changed (Pi clock)
    received_at: Mapped[datetime] = mapped_column(server_default=func.now())

    __table_args__ = (
        UniqueConstraint("home_id", "event_id", name="uq_events_home_id_event_id"),
        Index("ix_events_home_id_entity_id_occurred_at", "home_id", "entity_id", "occurred_at"),
    )


class Alert(Base):
    """Transactional outbox for watchdog alerts.

    The watchdog inserts the alert in the same transaction as the status change, then
    delivers it separately. A crash between "decided" and "sent" can't lose an alert;
    it gets delivered on the next run. Doubles as the audit trail of what was sent when.
    """

    __tablename__ = "alerts"

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    home_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("homes.id", ondelete="CASCADE"))
    kind: Mapped[str] = mapped_column(String(16))
    title: Mapped[str] = mapped_column(String(80))
    message: Mapped[str] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())
    delivered_at: Mapped[datetime | None]
    attempts: Mapped[int] = mapped_column(server_default=text("0"))
    last_error: Mapped[str | None] = mapped_column(String(200))

    __table_args__ = (
        CheckConstraint(_in_list("kind", ALERT_KINDS), name="kind"),
        Index(
            "ix_alerts_undelivered",
            "id",
            postgresql_where=text("delivered_at IS NULL"),
        ),
    )
